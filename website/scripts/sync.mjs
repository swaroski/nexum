// Pulls docs that live in the repository into the site, so there is one
// source of truth: ARCHITECTURE/THREAT_MODEL/ROADMAP, example guides,
// diagrams, and the reason-code table generated from nexum-core.
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = dirname(site);
const docs = join(site, "src/content/docs");
const blob = "https://github.com/swaroski/nexum/blob/main";

function page(out, title, body) {
  mkdirSync(dirname(join(docs, out)), { recursive: true });
  const note = `<!-- Generated by scripts/sync.mjs. Edit the source in the repository. -->\n\n`;
  writeFileSync(join(docs, out), `---\ntitle: ${JSON.stringify(title)}\n---\n\n${note}${body}`);
}

// Drop the H1 (Starlight renders the title) and point relative links at GitHub.
function adapt(src) {
  const md = readFileSync(join(repo, src), "utf8").replace(/^# .*\n/, "");
  const base = dirname(src);
  return md.replace(
    /\]\((?!https?:|#|mailto:)([^)\s]+)\)/g,
    (_, p) => `](${blob}/${join(base, p)})`,
  );
}

page("security/architecture.md", "Architecture", adapt("ARCHITECTURE.md"));
page("security/threat-model.md", "Threat model", adapt("THREAT_MODEL.md"));
page("project/roadmap.md", "Roadmap", adapt("ROADMAP.md"));
page("project/platform.md", "Platform plan", adapt("docs/PLATFORM.md"));
page("guides/mcp.md", "MCP tool firewall", adapt("examples/mcp/README.md"));
page("guides/a2a.md", "A2A agent-to-agent", adapt("examples/a2a/README.md"));
page("guides/python.md", "Python client", adapt("examples/python/README.md"));
page("guides/opa.md", "OPA (Rego) policies", adapt("examples/opa/README.md"));

// Reason codes, from the source of truth: meaning, pipeline stage and
// security event are parsed from nexum-core; why/fix come from
// src/reason-guide.mjs.
import guide, { rationale } from "../src/reason-guide.mjs";
const model = readFileSync(join(repo, "crates/nexum-core/src/model.rs"), "utf8");
const fnBody = (name) => {
  const at = model.indexOf(`pub fn ${name}(self)`);
  if (at < 0) throw new Error(`ReasonCode::${name} not found`);
  return model.slice(at).split("\n    }\n")[0];
};
// `A | B | C => value` arms; `value` may be wrapped in `{ }`.
function arms(body, valueRe) {
  const out = {};
  const re = new RegExp(String.raw`((?:\w+\s*\|\s*)*\w+)\s*=>\s*\{?\s*` + valueRe, "g");
  for (const m of body.matchAll(re)) {
    for (const name of m[1].split("|").map((x) => x.trim())) out[name] = m[2];
  }
  return out;
}
const codes = arms(fnBody("code"), String.raw`"([^"]+)"`);
const texts = arms(fnBody("describe"), String.raw`"([^"]+)"`);
const stages = arms(fnBody("stage"), String.raw`Stage::(\w+)`);
const events = arms(fnBody("security_event"), String.raw`(?:"([^"]+)"|return None)`);
if (Object.keys(codes).length < 40) throw new Error("reason code parse failed");
const snake = (n) => n.replace(/[A-Z]/g, (c, i) => (i ? "_" : "") + c.toLowerCase());
const slug = (code) => `errors/${code.toLowerCase()}`;
const outcomeOf = (code) =>
  ({ "NX-4001": "ALLOW", "NX-4003": "ALLOW", "NX-4002": "REQUIRE_APPROVAL" })[code] ?? "DENY";

const groups = {
  1: "Grant and chain validation",
  2: "Proof of possession",
  3: "Revocation",
  4: "Authority, trust, policy and approval",
  5: "Request and availability",
};
let table = `Every decision carries a stable \`NX-xxxx\` code. Codes are never reused.
Every code except \`NX-4001\`, \`NX-4002\` and \`NX-4003\` is a DENY. Each code
links to a page with causes and fixes; the CLI prints the same link.

The **security event** column is the stable name Nexum emits (span attribute
\`nexum.security_event\`, metric \`nexum_security_events_total{event=…}\`)
for denials worth alerting on.\n`;
for (const [g, title] of Object.entries(groups)) {
  table += `\n## ${title}\n\n| Code | Name | Meaning | Security event |\n|---|---|---|---|\n`;
  for (const [name, code] of Object.entries(codes).filter(([, c]) => c[3] === g)) {
    const ev = events[name] ? `\`${events[name]}\`` : "";
    table += `| [\`${code}\`](/nexum/${slug(code)}/) | \`${snake(name)}\` | ${texts[name] ?? ""} | ${ev} |\n`;
  }
}
page("reference/reason-codes.md", "Reason codes", table);

for (const [name, code] of Object.entries(codes)) {
  const g = guide[code];
  if (!g) throw new Error(`${code} has no entry in src/reason-guide.mjs`);
  const stage = (stages[name] ?? "").toLowerCase();
  if (!rationale[stage]) throw new Error(`${code}: unknown stage ${stage}`);
  const ev = events[name];
  page(
    `${slug(code)}.md`,
    `${code} ${snake(name).toUpperCase()}`,
    `**${outcomeOf(code)}** · stage: ${stage}${ev ? ` · security event: \`${ev}\`` : ""}

${texts[name]}

## Why it happens

${g.why}

## How to fix it

${g.fix}

## Why Nexum checks this

${rationale[stage]}

## Investigate

\`\`\`bash
nexum audit search --decision ${outcomeOf(code)}
nexum trace inspect <request-id>     # which check decided, and the delegation path
\`\`\`

See all [reason codes](/nexum/reference/reason-codes/).
`,
  );
}

// CLI reference from the binary's own --help, when one is available
// (NEXUM_BIN, or a local cargo build). Otherwise keep the committed page.
const bin = process.env.NEXUM_BIN ?? join(repo, "target/debug/nexum");
if (existsSync(bin)) {
  const help = (...a) => execFileSync(bin, [...a, "--help"], { encoding: "utf8" }).trim();
  const top = help();
  const cmds = [...top.split("Commands:")[1].split("Options:")[0].matchAll(/^  (\S+)/gm)]
    .map((m) => m[1])
    .filter((c) => c !== "help");
  let md = "Generated from `nexum --help`. Every command accepts `-c/--config` (env `NEXUM_CONFIG`, default `nexum.yaml`).\n\n```text\n" + top + "\n```\n";
  for (const c of cmds) {
    const sub = help(c);
    md += `\n## nexum ${c}\n\n\`\`\`text\n${sub}\n\`\`\`\n`;
    const subs = sub.includes("Commands:")
      ? [...sub.split("Commands:")[1].split("Options:")[0].matchAll(/^  (\S+)/gm)].map((m) => m[1]).filter((x) => x !== "help")
      : [];
    for (const s of subs) md += `\n### nexum ${c} ${s}\n\n\`\`\`text\n${help(c, s)}\n\`\`\`\n`;
  }
  page("reference/cli.md", "CLI", md);
}

